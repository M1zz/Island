var out: [String: [String: Any]] = [:]
func add(_ name: String, _ image: CGImage) {
    out[name] = ["w": image.width, "h": image.height, "png": NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])!.base64EncodedString()]
}
func half(_ image: CGImage) -> CGImage {
    let c = CGContext(data: nil, width: image.width / 2, height: image.height / 2, bitsPerComponent: 8, bytesPerRow: 0, space: CGColorSpace(name: CGColorSpace.sRGB)!, bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
    c.interpolationQuality = .none
    c.draw(image, in: CGRect(x: 0, y: 0, width: image.width / 2, height: image.height / 2))
    return c.makeImage()!
}
